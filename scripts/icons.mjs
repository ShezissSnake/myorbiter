// Renders every app icon file from the master, src-tauri/icons/icon.svg:
//   npm run icons             write the files
//   npm run icons -- --check  exit 1 if any file differs from what the master renders
//
// The master has two hull groups: #hull-detailed for 48 px and up, #hull-simple (a bolder drawing)
// below 48 px. Each size is rendered from a copy of the master with the other group taken out.
// Rendering uses librsvg's rsvg-convert (packaged as librsvg2-bin, librsvg2-tools or librsvg on
// most Linux distributions); .ico and .icns are packed here from those PNGs. Nothing in the output
// depends on the time, so running it again with the same rsvg-convert (and the same cairo and zlib
// underneath) gives the same bytes.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "src-tauri/icons");
const MASTER = join(DIR, "icon.svg");
const SMALL_BELOW = 48;

const GENERATED = "<!-- Generated by `npm run icons` from icon.svg's plate and small hull; edit icon.svg instead. -->";

/** The master's two renderable copies (each with one hull group taken out) and icon-small.svg's text. */
export function variants(master) {
  if ((master.match(/<g\b/g) ?? []).length !== 3) throw new Error("icon.svg: expected exactly three groups (#plate, #hull-detailed, #hull-simple), none nested");
  const group = (id) => new RegExp(`\\n?[ \\t]*<g id="${id}"[^>]*>[\\s\\S]*?</g>`);
  for (const id of ["plate", "hull-detailed", "hull-simple"]) if (!group(id).test(master)) throw new Error(`icon.svg: no <g id="${id}">`);
  const large = master.replace(group("hull-simple"), "");
  const small = master.replace(group("hull-detailed"), "").replace(/(<g id="hull-simple")\s+display="none"/, "$1");
  return { large, small, smallFile: small.replace(/<!--[\s\S]*?-->/, GENERATED) };
}

function render(svg, size) {
  const r = spawnSync("rsvg-convert", ["--width", String(size), "--height", String(size), "--format", "png"], { input: svg, maxBuffer: 64 << 20 });
  if (r.error) throw new Error(`rsvg-convert is needed to render the icons (${r.error.message})`);
  if (r.status !== 0) throw new Error(`rsvg-convert failed at ${size} px: ${r.stderr}`);
  return r.stdout;
}

// Windows .ico: a directory of PNG images (Windows Vista and later read PNG entries).
function ico(png, sizes) {
  const images = sizes.map(png);
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach((img, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(sizes[i] >= 256 ? 0 : sizes[i], e);
    head.writeUInt8(sizes[i] >= 256 ? 0 : sizes[i], e + 1);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(img.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += img.length;
  });
  return Buffer.concat([head, ...images]);
}

// macOS .icns: typed PNG entries. The pixel size is what is drawn, so a @2x entry of a 16 pt icon
// (32 px) uses the small drawing like any other 32 px image.
function icns(png, entries) {
  const parts = entries.map(([type, size]) => {
    const img = png(size);
    const h = Buffer.alloc(8);
    h.write(type, 0, "latin1");
    h.writeUInt32BE(8 + img.length, 4);
    return Buffer.concat([h, img]);
  });
  const h = Buffer.alloc(8);
  h.write("icns", 0, "latin1");
  h.writeUInt32BE(8 + parts.reduce((n, p) => n + p.length, 0), 4);
  return Buffer.concat([h, ...parts]);
}

function main() {
  const { large, small, smallFile } = variants(readFileSync(MASTER, "utf8"));
  const png = (size) => render(size < SMALL_BELOW ? small : large, size);
  const outputs = [
    ["32x32.png", () => png(32)],
    ["64x64.png", () => png(64)],
    ["128x128.png", () => png(128)],
    ["128x128@2x.png", () => png(256)],
    ["icon.png", () => png(512)],
    ["icon.ico", () => ico(png, [16, 24, 32, 48, 64, 256])],
    ["icon.icns", () => icns(png, [["icp4", 16], ["icp5", 32], ["ic11", 32], ["icp6", 64], ["ic12", 64], ["ic07", 128], ["ic08", 256], ["ic13", 256], ["ic09", 512], ["ic14", 512], ["ic10", 1024]])],
    // The small drawing as its own SVG, for places that show the mark at small sizes (the app's
    // sidebar, the site's header and favicon).
    ["icon-small.svg", () => Buffer.from(smallFile)],
  ];

  const check = process.argv.includes("--check");
  const stale = [];
  for (const [name, make] of outputs) {
    const file = join(DIR, name);
    const bytes = make();
    if (check) {
      if (!existsSync(file) || !readFileSync(file).equals(bytes)) stale.push(relative(ROOT, file));
    } else writeFileSync(file, bytes);
  }
  if (check && stale.length) {
    console.error(`Out of date with icon.svg (run npm run icons):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(check ? "Icons match icon.svg." : `Wrote ${outputs.length} files to ${relative(ROOT, DIR)}.`);
}

// Run only as a script, not when the tests import variants(); compared through realpath so a
// symlinked checkout still runs.
function isScript() {
  try {
    return realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
  } catch {
    return false;
  }
}
if (process.argv[1] && isScript()) main();
